def enrich(spec: dict) -> dict:
    """追加附件表格与补充 FAQ（不改变原 spec）。"""
    out = dict(spec)
    extra_sections = [
        S(a["heading"], a.get("intro", ""), [], table=a["table"])
        for a in APPENDICES.get(spec["doc_no"], [])
    ]
    out["sections"] = list(spec["sections"]) + extra_sections
    out["faq"] = list(spec.get("faq") or []) + FAQ_EXTRA.get(spec["doc_no"], [])
    return out


