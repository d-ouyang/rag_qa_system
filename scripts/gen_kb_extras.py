def _pdf_styles():
    from reportlab.lib.styles import ParagraphStyle
    from reportlab.lib.enums import TA_CENTER, TA_JUSTIFY
    from reportlab.lib import colors

    base = dict(fontName="ArialUnicode", wordWrap="CJK")
    return {
        "title": ParagraphStyle("title", fontSize=22, leading=30, alignment=TA_CENTER,
                                spaceAfter=10, textColor=colors.HexColor("#1a2a44"), **base),
        "subtitle": ParagraphStyle("subtitle", fontSize=12, leading=18, alignment=TA_CENTER,
                                   spaceAfter=4, textColor=colors.HexColor("#4a5a74"), **base),
        "meta": ParagraphStyle("meta", fontSize=9.5, leading=15, alignment=TA_CENTER,
                               textColor=colors.HexColor("#6b778c"), **base),
        "h1": ParagraphStyle("h1", fontSize=14, leading=21, spaceBefore=14, spaceAfter=6,
                             textColor=colors.HexColor("#1a2a44"), **base),
        "body": ParagraphStyle("body", fontSize=10.5, leading=18, alignment=TA_JUSTIFY,
                               spaceAfter=5, firstLineIndent=0, **base),
        "clause": ParagraphStyle("clause", fontSize=10.5, leading=18, alignment=TA_JUSTIFY,
                                 spaceAfter=5, leftIndent=0, firstLineIndent=0, **base),
        "cell": ParagraphStyle("cell", fontSize=8.5, leading=13, **base),
        "cell_head": ParagraphStyle("cell_head", fontSize=8.5, leading=13,
                                    textColor=colors.white, **base),
    }


def write_pdf(spec: dict, path: Path) -> None:
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.units import mm
    from reportlab.lib import colors
    from reportlab.pdfbase import pdfmetrics
    from reportlab.pdfbase.ttfonts import TTFont
    from reportlab.platypus import (SimpleDocTemplate, Paragraph, Spacer, Table,
                                    TableStyle, PageBreak)

    pdfmetrics.registerFont(TTFont("ArialUnicode", FONT_PATH))
    styles = _pdf_styles()
    path.parent.mkdir(parents=True, exist_ok=True)
    doc = SimpleDocTemplate(
        str(path), pagesize=A4,
        leftMargin=20 * mm, rightMargin=20 * mm,
        topMargin=18 * mm, bottomMargin=18 * mm,
        title=spec["title"], author=spec["owner"],
    )
    story: list = [
        Spacer(1, 40 * mm),
        Paragraph(xml_escape(spec["title"]), styles["title"]),
        Paragraph(xml_escape(spec["subtitle"]), styles["subtitle"]),
        Spacer(1, 12 * mm),
        Paragraph(f"文件编号：{xml_escape(spec['doc_no'])}", styles["meta"]),
        Paragraph(f"版本：{xml_escape(spec['version'])}", styles["meta"]),
        Paragraph(f"生效日期：{xml_escape(spec['effective'])}", styles["meta"]),
        Paragraph(f"归口部门：{xml_escape(spec['owner'])}", styles["meta"]),
        Paragraph("密级：内部", styles["meta"]),
        PageBreak(),
    ]
    clause_no = 0
    for section in spec["sections"]:
        story.append(Paragraph(xml_escape(section["heading"]), styles["h1"]))
        if section.get("intro"):
            story.append(Paragraph(xml_escape(section["intro"]), styles["body"]))
        for clause in section.get("clauses") or []:
            clause_no += 1
            story.append(Paragraph(f"第{clause_no}条　{xml_escape(clause)}", styles["clause"]))
        table = section.get("table")
        if table:
            data = [[Paragraph(xml_escape(str(c)), styles["cell_head"]) for c in table["headers"]]]
            for row in table["rows"]:
                data.append([Paragraph(xml_escape(str(c)), styles["cell"]) for c in row])
            col_w = (A4[0] - 40 * mm) / len(table["headers"])
            t = Table(data, colWidths=[col_w] * len(table["headers"]), repeatRows=1)
            t.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#2c4a72")),
                ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#c9d2e0")),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ("TOPPADDING", (0, 0), (-1, -1), 4),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f5f7fa")]),
            ]))
            story.append(Spacer(1, 4))
            story.append(t)
        story.append(Spacer(1, 4))

    if spec.get("faq"):
        story.append(PageBreak())
        story.append(Paragraph("附录：常见问题", styles["h1"]))
        for i, (q, a) in enumerate(spec["faq"], 1):
            story.append(Paragraph(f"问{i}：{xml_escape(q)}", styles["clause"]))
            story.append(Paragraph(f"答：{xml_escape(a)}", styles["body"]))

    def footer(canvas, _doc):
        canvas.saveState()
        canvas.setFont("ArialUnicode", 8.5)
        canvas.setFillColor(colors.HexColor("#8a94a6"))
        canvas.drawCentredString(A4[0] / 2, 10 * mm, f"第 {canvas.getPageNumber()} 页")
        canvas.restoreState()

    doc.build(story, onFirstPage=footer, onLaterPages=footer)


def write_docx(spec: dict, path: Path) -> None:
    from docx import Document
    from docx.shared import Pt, Cm, RGBColor
    from docx.enum.text import WD_ALIGN_PARAGRAPH
    from docx.enum.table import WD_TABLE_ALIGNMENT
    from docx.oxml.ns import qn

    def set_run(run, size=10.5, bold=False, color=None):
        run.font.name = "Arial Unicode MS"
        run._element.rPr.rFonts.set(qn("w:eastAsia"), "微软雅黑")
        run.font.size = Pt(size)
        run.bold = bold
        if color:
            run.font.color.rgb = RGBColor(*color)

    doc = Document()
    doc.styles["Normal"].font.name = "Arial Unicode MS"
    doc.styles["Normal"]._element.rPr.rFonts.set(qn("w:eastAsia"), "微软雅黑")
    for section in doc.sections:
        section.top_margin = Cm(2)
        section.bottom_margin = Cm(2)
        section.left_margin = Cm(2.4)
        section.right_margin = Cm(2.4)

    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    set_run(p.add_run(spec["title"]), 20, True, (0x1a, 0x2a, 0x44))
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    set_run(p.add_run(spec["subtitle"]), 11, False, (0x4a, 0x5a, 0x74))
    for line in (
        f"文件编号：{spec['doc_no']}",
        f"版本：{spec['version']}",
        f"生效日期：{spec['effective']}",
        f"归口部门：{spec['owner']}",
        "密级：内部",
    ):
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        set_run(p.add_run(line), 9, False, (0x6b, 0x77, 0x8c))
    doc.add_page_break()

    clause_no = 0
    for section in spec["sections"]:
        p = doc.add_paragraph()
        set_run(p.add_run(section["heading"]), 14, True, (0x1a, 0x2a, 0x44))
        if section.get("intro"):
            p = doc.add_paragraph()
            set_run(p.add_run(section["intro"]), 10.5)
        for clause in section.get("clauses") or []:
            clause_no += 1
            p = doc.add_paragraph()
            set_run(p.add_run(f"第{clause_no}条　{clause}"), 10.5)
        table = section.get("table")
        if table:
            t = doc.add_table(rows=1, cols=len(table["headers"]))
            t.style = "Table Grid"
            t.alignment = WD_TABLE_ALIGNMENT.CENTER
            for i, h in enumerate(table["headers"]):
                cell = t.rows[0].cells[i]
                cell.text = ""
                set_run(cell.paragraphs[0].add_run(str(h)), 9, True)
            for row in table["rows"]:
                cells = t.add_row().cells
                for i, c in enumerate(row):
                    cells[i].text = ""
                    set_run(cells[i].paragraphs[0].add_run(str(c)), 9)
            doc.add_paragraph()
        doc.add_paragraph()

    if spec.get("faq"):
        doc.add_page_break()
        p = doc.add_paragraph()
        set_run(p.add_run("附录：常见问题"), 14, True, (0x1a, 0x2a, 0x44))
        for i, (q, a) in enumerate(spec["faq"], 1):
            p = doc.add_paragraph()
            set_run(p.add_run(f"问{i}：{q}"), 10.5, True)
            p = doc.add_paragraph()
            set_run(p.add_run(f"答：{a}"), 10.5)

    path.parent.mkdir(parents=True, exist_ok=True)
    doc.save(str(path))


